# Profundizando en los sistemas de numeración

#Sistema decimal
a = 10
print(f"a decimal: {a}")

#Sistema Binario
a = 0b1010
print(f"a binario: {a}")

#Sistema Octal
a = 0o12
print(f"a octal: {a}")

#Sistema Hexadecimal
a = 0xA
print(f"a hexadecimal: {a}")

#Base Decimal
a = int('23', 10)
print(f"a = base decimal: {a}")

#Base Binario
a = int('10111', 2)
print(f"a = base binario: {a}")

#Base Octal
a = int('27', 8) #buscar calculadora sistema numerico
print(f" a = base octal: {a}")

#Base Hexadecimal
a = int('17', 16) #buscar el valor hexadecimal de 23 es 17
print(f" a = base hexadecimal: {a}")

# Base 5 sus valores son de 0 a 4
a = int('34', 5)
print(f" a = Base 5: {a}")



